// Fallback faces for the web fonts. Each is a local system font resized to the web font's metrics (`size-adjust`
// and the ascent/descent overrides), so text does not reflow when the web font replaces it. The faces are written to
// src/theme/fonts.css by `npm run theme:build`; the stacks in src/index.css name them.

import { createFontStack } from '@capsizecss/core'
import arial from '@capsizecss/metrics/arial'
import courierNew from '@capsizecss/metrics/courierNew'
import georgia from '@capsizecss/metrics/georgia'
import geist from '@capsizecss/metrics/geist'
import geistMono from '@capsizecss/metrics/geistMono'
import newsreader from '@capsizecss/metrics/newsreader'

/** `[web font, the system font that stands in for it]`; the generated family is "<web font family> Fallback". */
const PAIRS = [
  [geist, arial],
  [geistMono, courierNew],
  [newsreader, georgia],
] as const

export function fontFacesCss(): string {
  const faces = PAIRS.map(([font, fallback]) => createFontStack([font, fallback]).fontFaces.trim())
  return `/* Generated by scripts/theme.ts from src/theme/fonts.ts. Do not edit. */\n${faces.join('\n\n')}\n`
}
